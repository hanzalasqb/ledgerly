#!/usr/bin/env node
/**
 * Turns design/tokens.json (W3C Design Tokens, the format Figma's Tokens Studio exports)
 * into CSS custom properties: primitives, light theme on :root, dark theme on [data-theme="dark"].
 */
import { readFileSync, writeFileSync } from "node:fs";

const OUT = "apps/web/src/styles/tokens.css";
const tokens = JSON.parse(readFileSync("design/tokens.json", "utf8"));

const get = (path) => path.split(".").reduce((o, k) => o?.[k], tokens);
const resolve = (v) => (typeof v === "string" ? v.replace(/\{([^}]+)\}/g, (_, p) => resolve(get(p)?.$value)) : v);
const value = (t) => (t.$type === "cubicBezier" ? `cubic-bezier(${t.$value.join(", ")})` : resolve(t.$value));

function flatten(node, prefix, out = []) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith("$")) continue;
    if (v && typeof v === "object" && "$value" in v) out.push([`--${[...prefix, k].join("-")}`, value(v)]);
    else if (v && typeof v === "object") flatten(v, [...prefix, k], out);
  }
  return out;
}

const block = (sel, vars) => `${sel} {\n${vars.map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n`;
const { theme, ...rest } = tokens;
const css = [
  "/* Generated by scripts/build-tokens.mjs from design/tokens.json. Do not edit by hand. */\n",
  block(":root", [...flatten(rest, []), ...flatten(theme.light, ["color"])]),
  block(':root[data-theme="dark"]', flatten(theme.dark, ["color"])),
].join("\n");

writeFileSync(OUT, css);
console.log(`Wrote ${OUT}`);
